# Dictionary is a way of storing data and indexing in the form of strings instead of numbers
menu = dict(Starter = 'Soup',
            Main_Course = 'Butter Chicken',
            Drink = 'Mojito',
            Desert = 'Brownie')
print(menu)

# Another way of defining and then initialising:

codes = {}
codes["red"] = "Emergency"
codes["yellow"] = "Attention"
print(codes)

del codes["red"] # deletion
print(codes)

