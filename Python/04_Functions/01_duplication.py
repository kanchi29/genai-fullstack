# every function starts with a keyword def followed by the function name and the parameter(s).

# Syntax: def [function_name] ([parameters])

def print_order(name, order):
    print(f"{name}'s order is {order}!")

print_order("Kanchi", "burger")
print_order("Adarshita", "pizza")
print_order("Abhishek", "noodles")